"""Единые бюджеты времени для тестов.

Зачем модуль. В репозитории 90 мест меряют wallclock, и в ReDoS-защитах пороги
разъехались от 0.05 с до 5.0 с — хотя защищают все от ОДНОГО И ТОГО ЖЕ:
катастрофического бэктрекинга регулярного выражения.

🔴 Ключевое наблюдение: катастрофический ReDoS — это не «немного медленнее», а
экспоненциальный взрыв в СЕКУНДЫ И МИНУТЫ. Нормальная работа тех же функций —
единицы миллисекунд. Между этими режимами зазор в три-четыре порядка, поэтому
порог 0.05 с и порог 5.0 с ловят ровно одно и то же. Разница только в том, что
узкий порог вдобавок ловит загруженную машину и красит здоровый код в красный.

Живые падения, из-за которых заведён модуль (self-hosted раннер, август 2026):

- `test_metadata_enricher_W1765`: 0.350 с и 0.463 с при пороге 0.3 с;
- `test_email_sender_W1747`: 1.543 с при пороге 1.5 с;
- `test_audit_purge_coverage`: 10.7 с при пороге 5.0 с — там wallclock вовсе
  заменили счётчиком вызовов `ast.walk()`, см. комментарий в том файле.

Разброс на одной и той же машине доходил до 5× без изменений в коде: раннер
делит CPU с приложениями владельца, LM Studio и параллельными сборками.

Когда wallclock НЕ годится вовсе. Если тест проверяет «алгоритм не стал
квадратичным», измеряй структурную величину — число вызовов, число проходов по
дереву, количество запросов. Такая величина зависит только от кода и не зависит
от того, чем занята машина. Образец — `test_audit_purge_coverage.py`.
"""
